function trInline(core: string, lg: 'hi' | 'bn'): string {
  let out = core;
  let changed = false;
  TR_WORDS.forEach((r) => {
    const v = r[lg === 'hi' ? 1 : 2];
    if (out.indexOf(r[0]) >= 0) {
      out = out.split(r[0]).join(v);
      changed = true;
    }
  });
  return changed ? out : core;
}

export function trStr(s: string, lang: PdaLang): string {
  if (lang === 'en' || !s) return s;
  const leadMatch = s.match(/^\s*/);
  const trailMatch = s.match(/\s*$/);
  const lead = leadMatch ? leadMatch[0] : '';
  const trail = trailMatch ? trailMatch[0] : '';
  const core = s.trim();
  if (!core) return s;
  const lg = lang;
  const t = (x: string) => {
    const h = TR_MAP[x];
    return h && h[lg] ? h[lg] : x;
  };
  const hit = TR_MAP[core];
  if (hit && hit[lg]) return lead + hit[lg] + trail;
  for (let i = 0; i < TR_RULES.length; i++) {
    const m = core.match(TR_RULES[i][0]);
    if (m) return lead + trInline(TR_RULES[i][lg === 'hi' ? 1 : 2](m, t), lg) + trail;
  }
  const inl = trInline(core, lg);
  if (inl !== core) return lead + inl + trail;
  return s;
}

export function T(key: string, lang: PdaLang): string {
  if (lang !== 'en' && I18N[lang] && I18N[lang][key]) return I18N[lang][key];
  return STR[key] || key;
}
